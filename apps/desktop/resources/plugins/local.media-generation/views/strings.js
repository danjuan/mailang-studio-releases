"use strict";

function formatLongSegments(durations, formatSeconds) {
  const groups = [];
  for (const seconds of durations) {
    const previous = groups.at(-1);
    if (previous?.seconds === seconds) previous.count++;
    else groups.push({ seconds, count: 1 });
  }
  return groups.map(({ seconds, count }) => count > 1 ? `${formatSeconds(seconds)} × ${count}` : formatSeconds(seconds)).join(" + ");
}

